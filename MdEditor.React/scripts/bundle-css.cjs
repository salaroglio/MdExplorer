function createBundle(outputFile, header) {
  let bundledCss = `/*
 * ${header}
 * Auto-generated by bundle-css.cjs
 * DO NOT EDIT MANUALLY
 */\n\n`;

  for (const cssFile of cssFiles) {
    const fullPath = path.join(nodeModules, cssFile);

    if (fs.existsSync(fullPath)) {
      const content = fs.readFileSync(fullPath, 'utf8');
      // Rimuovi @import statements (li abbiamo già inclusi)
      const cleanContent = content.replace(/@import\s+['"][^'"]+['"];?\s*/g, '');
      bundledCss += `/* === ${cssFile} === */\n${cleanContent}\n\n`;
      console.log(`  Added: ${cssFile}`);
    } else {
      console.warn(`  Warning: File not found: ${fullPath}`);
    }
  }

  // Aggiungi stili personalizzati
  bundledCss += customStyles;

  fs.writeFileSync(outputFile, bundledCss);
  console.log(`Bundle created: ${outputFile}`);
  console.log(`Total size: ${(Buffer.byteLength(bundledCss) / 1024).toFixed(2)} KB\n`);
}

// Crea bundle per sviluppo
