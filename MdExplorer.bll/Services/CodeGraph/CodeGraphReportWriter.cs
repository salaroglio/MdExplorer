using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Threading;
using System.Threading.Tasks;

namespace MdExplorer.Features.Services.CodeGraph
{
    /// <summary>
    /// Il report del grafo del codice (F6, su Fuseki da F7): <c>.md/codegraph/report.md</c>, rigenerato dopo ogni analisi e dopo ogni
    /// giro di descrizioni. Dice che cosa c'è e che cosa manca: simboli più connessi, file più grossi, simboli senza
    /// descrizione, descrizioni da rivedere, archi ambigui. Scritto con le convenzioni di mde-doc (TL;DR in testa), nella
    /// lingua dell'interfaccia (it, en).
    /// </summary>
    public sealed class CodeGraphReportWriter
    {
        private readonly ICodeGraphStore _store;
        private readonly IUiLanguage _language;
        public CodeGraphReportWriter(ICodeGraphStore store, IUiLanguage language) { _store = store; _language = language; }

        public static string ReportRelativePath => ".md/codegraph/report.md";
        public static string ReportPath(string projectPath) => Path.Combine(projectPath, ".md", "codegraph", "report.md");

        public async Task<string> WriteAsync(string projectPath, IReadOnlyList<string> notes = null, CancellationToken ct = default)
        {
            var data = await _store.GetReportDataAsync(projectPath, ct);
            var o = data.Overview;
            var undescribed = data.Undescribed;
            var ambiguous = data.Ambiguous;
            var inferred = data.Inferred;
            var stale = data.StaleList;
            var ambiguousList = data.AmbiguousList;
            var undescribedList = data.UndescribedList;
            var it = _language.Current == "it";
            string L(string italian, string english) => it ? italian : english;

            var sb = new StringBuilder();
            sb.AppendLine("---");
            sb.AppendLine(L("title: Grafo del codice — report", "title: Code graph — report"));
            sb.AppendLine("---");
            sb.AppendLine();
            sb.AppendLine(L("# Grafo del codice — report", "# Code graph — report"));
            sb.AppendLine();
            sb.AppendLine("## TL;DR");
            sb.AppendLine(L($"Il grafo del codice di questo progetto ha {o.Files} file, {o.Symbols} simboli e {o.Edges} archi, generato da MdExplorer il {DateTime.Now:dd/MM/yyyy HH:mm}. Questo report è rigenerato a ogni analisi e a ogni giro di descrizioni: dice che cosa c'è e che cosa manca.",
                $"The code graph of this project has {o.Files} files, {o.Symbols} symbols and {o.Edges} edges, generated by MdExplorer on {DateTime.Now:yyyy-MM-dd HH:mm}. This report is rewritten at every analysis and every round of descriptions: it says what is there and what is missing."));
            sb.AppendLine();
            sb.AppendLine(L($"- {o.DescribedSymbols} simboli descritti e {o.DescribedFiles} file su {o.Files} con la loro utilità, {undescribed} ancora senza descrizione, {stale.Count} descrizioni da rivedere (firma cambiata).",
                $"- {o.DescribedSymbols} symbols described and {o.DescribedFiles} files out of {o.Files} with what they are for, {undescribed} still without a description, {stale.Count} descriptions to review (signature changed)."));
            sb.AppendLine(L($"- {ambiguous} archi ambigui e {inferred} inferiti: le chiamate che l'analisi ha risolto per nome, non con certezza.",
                $"- {ambiguous} ambiguous and {inferred} inferred edges: the calls the analysis resolved by name, not with certainty."));
            if (data.LlmResolved > 0)
                sb.AppendLine(L($"- {data.LlmResolved} chiamate ambigue risolte dall'LLM mentre descriveva il codice (certezza `llm-resolved`): le altre candidate non si mostrano più, ma restano negli script AST.",
                    $"- {data.LlmResolved} ambiguous calls resolved by the LLM while describing the code (confidence `llm-resolved`): the other candidates are no longer shown, but they stay in the AST scripts."));
            var none = L("nessuno", "none");
            var mostConnected = o.MostConnected.Count > 0 ? "`" + o.MostConnected[0].Symbol.QualifiedName + "`" : none;
            var largest = o.LargestFiles.Count > 0 ? "`" + o.LargestFiles[0].Path + "`" : none;
            sb.AppendLine(L($"- Il simbolo più connesso è {mostConnected}; il file più grosso è {largest}.", $"- The most connected symbol is {mostConnected}; the largest file is {largest}."));
            sb.AppendLine();
            sb.AppendLine(L("## Di che cosa è fatto", "## What it is made of"));
            sb.AppendLine();
            sb.AppendLine(L("| Linguaggio | Simboli |", "| Language | Symbols |"));
            sb.AppendLine("|---|---|");
            foreach (var kv in o.SymbolsByLanguage.OrderByDescending(k => k.Value)) sb.AppendLine($"| {kv.Key} | {kv.Value} |");
            sb.AppendLine();
            sb.AppendLine(L("| Relazione | Archi |", "| Relation | Edges |"));
            sb.AppendLine("|---|---|");
            foreach (var kv in o.EdgesByRelation.OrderByDescending(k => k.Value)) sb.AppendLine($"| {kv.Key} | {kv.Value} |");
            sb.AppendLine();
            sb.AppendLine(L("## I simboli più connessi", "## The most connected symbols"));
            sb.AppendLine();
            sb.AppendLine(L("| Simbolo | Tipo | Archi | File |", "| Symbol | Kind | Edges | File |"));
            sb.AppendLine("|---|---|---|---|");
            foreach (var (s, deg) in o.MostConnected) sb.AppendLine($"| `{s.QualifiedName}` | {s.Kind} | {deg} | {s.Path}:{s.LineStart} |");
            sb.AppendLine();
            sb.AppendLine(L("## I file più grossi", "## The largest files"));
            sb.AppendLine();
            sb.AppendLine(L("| File | Simboli | A che cosa serve |", "| File | Symbols | What it is for |"));
            sb.AppendLine("|---|---|---|");
            foreach (var (filePath, n, summary) in o.LargestFiles) sb.AppendLine($"| {filePath} | {n} | {(summary ?? "—").Replace("|", "\\|").Replace('\n', ' ')} |");
            sb.AppendLine();
            sb.AppendLine(L("## Senza descrizione", "## Without a description"));
            sb.AppendLine();
            if (undescribed == 0) sb.AppendLine(L("Tutti i simboli hanno una descrizione.", "Every symbol has a description."));
            else
            {
                sb.AppendLine(L($"{undescribed} simboli. «Descrivi con Mark» nella finestra Ambiente di sviluppo li completa. I primi {undescribedList.Count}:",
                    $"{undescribed} symbols. «Describe with Mark» in the Development environment window completes them. The first {undescribedList.Count}:"));
                sb.AppendLine();
                foreach (var r in undescribedList) sb.AppendLine($"- {r[0]} `{r[1]}` — {r[2]}:{r[3]}");
            }
            sb.AppendLine();
            sb.AppendLine(L("## Descrizioni da rivedere", "## Descriptions to review"));
            sb.AppendLine();
            if (stale.Count == 0) sb.AppendLine(L("Nessuna: ogni descrizione corrisponde alla firma attuale.", "None: every description matches the current signature."));
            else foreach (var r in stale) sb.AppendLine($"- `{r[0]}` — {r[1]}:{r[2]} ({L("la firma è cambiata dopo la descrizione", "the signature changed after the description")})");
            sb.AppendLine();
            sb.AppendLine(L("## Archi ambigui", "## Ambiguous edges"));
            sb.AppendLine();
            if (ambiguous == 0) sb.AppendLine(L("Nessuno.", "None."));
            else
            {
                sb.AppendLine(L($"{ambiguous} archi risolti per nome con più candidati o nessuno (nodo external). I primi {ambiguousList.Count}:",
                    $"{ambiguous} edges resolved by name with several candidates or none (external node). The first {ambiguousList.Count}:"));
                sb.AppendLine();
                foreach (var r in ambiguousList) sb.AppendLine($"- `{r[0]}` {r[1]} `{r[2]}` — {r[3]}:{r[4]}");
            }
            if (notes != null && notes.Count > 0)
            {
                sb.AppendLine();
                sb.AppendLine(L("## Note dell'ultima analisi", "## Notes of the last analysis"));
                sb.AppendLine();
                foreach (var n in notes) sb.AppendLine($"- {n}");
            }

            var path = ReportPath(projectPath);
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, sb.ToString(), new UTF8Encoding(false));
            return path;
        }
    }
}
